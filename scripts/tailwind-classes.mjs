// Collects every class-name candidate used under src/ and hands them to Tailwind through
// `@source inline(...)` in src/app/tailwind-sources.css.
//
// Why: Tailwind v4 finds classes with a native file scanner (@tailwindcss/oxide). Where that binary
// can't load — e.g. Windows with Smart App Control / application control blocking unsigned .node
// files — Tailwind falls back to a WebAssembly scanner that cannot read Windows drive paths, finds
// nothing, and the app renders unstyled. Inline sources need no scanning, so the styles are the same
// on every machine. On machines where the native scanner works this is harmless duplication.
//
//   node scripts/tailwind-classes.mjs          generate once
//   node scripts/tailwind-classes.mjs --watch  generate, then regenerate on every change under src/

import { promises as fs, watch as fsWatch } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'src');
const outFile = path.join(srcDir, 'app', 'tailwind-sources.css');

async function* walk(dir) {
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (/\.(tsx?|jsx?|mdx)$/.test(entry.name)) yield full;
  }
}

// Every quoted string in the source; template literals lose their ${…} parts first.
const STRING = /'([^'\\\n]*(?:\\.[^'\\\n]*)*)'|"([^"\\\n]*(?:\\.[^"\\\n]*)*)"|`([^`]*)`/g;
// What a utility can look like. Anything else (and anything with quotes, braces or backslashes,
// which would break the inline() string) is skipped; unknown tokens are simply ignored by Tailwind.
const CANDIDATE = /^[!-]?(?:[a-z@[*]|[2-9]xl:)[^\s"'\\{}`]*$/i;

export async function generate() {
  const tokens = new Set();
  for await (const file of walk(srcDir)) {
    const text = await fs.readFile(file, 'utf8');
    for (const m of text.matchAll(STRING)) {
      const body = (m[1] ?? m[2] ?? m[3] ?? '').replace(/\$\{[^}]*\}/g, ' ');
      for (const token of body.split(/\s+/)) {
        if (token.length > 1 && token.length < 200 && CANDIDATE.test(token)) tokens.add(token);
      }
    }
  }

  const sorted = [...tokens].sort();
  const lines = [];
  for (let i = 0; i < sorted.length; i += 150) lines.push(`@source inline("${sorted.slice(i, i + 150).join(' ')}");`);
  const css = `/* Generated by scripts/tailwind-classes.mjs — do not edit by hand. See that file for why. */\n${lines.join('\n')}\n`;

  const current = await fs.readFile(outFile, 'utf8').catch(() => '');
  if (current !== css) {
    await fs.writeFile(outFile, css);
    return { changed: true, count: sorted.length };
  }
  return { changed: false, count: sorted.length };
}

export function watch() {
  let timer = null;
  const watcher = fsWatch(srcDir, { recursive: true }, (_event, file) => {
    if (!file || path.join(srcDir, file) === outFile) return;
    clearTimeout(timer);
    timer = setTimeout(() => {
      generate()
        .then((r) => r.changed && console.log(`[tailwind-classes] updated (${r.count} candidates)`))
        .catch((e) => console.error('[tailwind-classes]', e.message));
    }, 120);
  });
  return () => watcher.close();
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await generate();
  console.log(`[tailwind-classes] ${result.count} candidates → src/app/tailwind-sources.css`);
  if (process.argv.includes('--watch')) {
    watch();
    console.log('[tailwind-classes] watching src/');
  }
}
